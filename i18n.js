let LANG = 'bn';
export function getLang() { return LANG; }
export function setLang(l) {
  LANG = (l === 'en' || l === 'mixed') ? l : 'bn';
  try { localStorage.setItem('ap.uiLang', LANG); } catch {}
}
export function t(key, vars) {
  const e = D[key];
  let s = e ? e[LANG === 'en' ? 1 : 0] : key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, v);
  return s;
}
export function en(key, vars) {
  const e = D[key];
  let s = e ? e[1] : key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, v);
  return s;
}
/* mixed-mode secondary English string for headings */
export function sub(key) {
  const e = D[key];
  return e ? e[1] : '';
}

export function applyStatic(root = document) {
  root.querySelectorAll('[data-i18n]').forEach(n => { n.textContent = t(n.getAttribute('data-i18n')); });
  root.querySelectorAll('[data-i18n-aria]').forEach(n => { n.setAttribute('aria-label', t(n.getAttribute('data-i18n-aria'))); });
  root.querySelectorAll('[data-i18n-ph]').forEach(n => { n.setAttribute('placeholder', t(n.getAttribute('data-i18n-ph'))); });
  root.querySelectorAll('.nav-sub').forEach(n => {
    const k = n.getAttribute('data-i18n-en');
    if (k) n.textContent = sub(k);
  });
  document.documentElement.setAttribute('data-lang', LANG);
  document.documentElement.lang = LANG === 'en' ? 'en' : 'bn';
}
